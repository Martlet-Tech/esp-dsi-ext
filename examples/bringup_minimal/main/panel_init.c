/*
 * 最小初始化表 —— 只用到 MIPI DCS 里的公共命令。
 *
 * ★ 这张表**不保证点亮任何具体面板**。它的作用有两个：
 *   1) 让工程能编、能跑、能出图，用来验证 DSI 通路本身；
 *   2) 作为格式模板 —— 把你自己的初始化序列按同样的 {dt, delay, len, data[]}
 *      填进来就行，屏幕相关的逻辑一行都不用动。
 *
 * 换表的办法：把供应商给的序列逐条翻译过来，表尾保留 11h / 29h。
 *   - lua 的 write_reg(0xBB, {...})  -> {0x39, 0, 3+N, {0xBB, ...}}
 *   - C 数组 {0xBB, 0x01, 0x02}      -> {0x39, 0, 3, {0xBB, 0x01, 0x02}}
 *   - 只有寄存器没有参数             -> {0x05, 0, 1, {0x11}}
 *   - 参数只有 1 个                   -> {0x15, 0, 2, {0x51, 0xFF}}
 * 参数 ≥2 个一律用长写（0x39 或 0x29）。
 *
 * 表里出现 0x29 时要注意：它既是"DCS 长写"的常见命令号（display on），
 * 也是"Generic 长写"的 DT。这两件事在本结构里分别由 dt 字段和 data[0]
 * 表达，不冲突 —— 但看日志时别混。
 */

#include "panel_init.h"

const panel_cmd_t g_panel_init[] = {
    /*  DT, delay, len, { 命令, 参数... } */

    /* 3Ah COLMOD: 0x77 = 24bpp。有些面板忽略这一条（格式由 DSI 包的
     * DT 决定），发它无害，留着当"带参数命令"的示例。
     * 若你的屏是 RGB565，改成 0x55。 */
    { 0x15,   0,  2, {0x3A, 0x77, } },

    /* 11h sleep out。spec 要求 5ms 后可以发下一条，实际给 120ms 更稳。 */
    { 0x05, 120,  1, {0x11, } },

    /* 29h display on。之后才能出图。 */
    { 0x05,  20,  1, {0x29, } },
};

const int g_panel_init_count = sizeof(g_panel_init) / sizeof(g_panel_init[0]);
